HONORIFIC_RULES = [
    ("§6", "평어체 잔존 (존대 문서만)", r"(이다\.|한다\.|된다\.)", False),
]


WEEKDAY = re.compile(r"[월화수목금토일](·[월화수목금토일])+")


def scan(path, rules):
    hits = 0
    with open(path, encoding="utf-8") as fh:
        raw = fh.read().split("\n")
    lines, fence = [], False
    for ln in raw:                                  # 코드 블록 안은 검사하지 않음
        if ln.lstrip().startswith(("```", "~~~")):
            fence = not fence
            lines.append("")
            continue
        lines.append("" if fence else ln)
    for rule, desc, pat, manual in rules:
        rx = re.compile(pat)
        if rule == "§8.15":
            found = [(i + 1, ln) for i, ln in enumerate(lines) if rx.search(WEEKDAY.sub("", ln))]
        else:
            found = [(i + 1, ln) for i, ln in enumerate(lines) if rx.search(ln)]
        if not found:
            continue
        tag = " (수동 확인)" if manual else ""
        print(f"## {rule} {desc}{tag}")
        for n, ln in found:
            m = rx.search(ln)
            print(f"  {path}:{n}: {ln.strip()[:120]}  ← {m.group(0)!r}")
        hits += len(found)
    return hits


def main(argv):
    honorific = "--honorific" in argv
    files = [a for a in argv if not a.startswith("--")]
    if not files:
        print(__doc__)
        return 2
    rules = RULES + (HONORIFIC_RULES if honorific else [])
    total = sum(scan(f, rules) for f in files)
    print(f"hits: {total}")
    return 1 if total else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
